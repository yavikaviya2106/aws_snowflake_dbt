SELECT 
BOOKING_ID,
LISTING_ID,
CAST(BOOKING_DATE AS TIMESTAMP) AS BOOKING_DATE,
CAST(NIGHTS_BOOKED AS INTEGER) AS NIGHTS_BOOKED,
CAST(BOOKING_AMOUNT AS NUMERIC(10,2)) AS BOOKING_AMOUNT,
CAST(CLEANING_FEE AS NUMERIC(10,2)) AS CLEANING_FEE,
CAST(SERVICE_FEE AS NUMERIC(10,2)) AS SERVICE_FEE,
CAST(BOOKING_STATUS AS STRING) AS BOOKING_STATUS,
CAST(CREATED_AT AS TIMESTAMP)AS CREATED_AT

FROM {{source('source','bookings')}}



