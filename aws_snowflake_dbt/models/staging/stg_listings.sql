SELECT 
LISTING_ID,
HOST_ID,
UPPER(TRIM(PROPERTY_TYPE)) AS PROPERTY_TYPE,
UPPER(TRIM(ROOM_TYPE)) AS ROOM_TYPE,
UPPER(TRIM(CITY)) AS CITY,
UPPER(TRIM(COUNTRY)) AS COUNTRY,
CAST(ACCOMMODATES AS INTEGER) AS ACCOMMODATES,
CAST(BEDROOMS AS INTEGER) AS BEDROOMS,
CAST(BATHROOMS AS NUMERIC(3,1)) AS BATHROOMS,
CAST(PRICE_PER_NIGHT AS NUMERIC(10,2)) AS PRICE_PER_NIGHT,
CAST(CREATED_AT AS TIMESTAMP) AS CREATED_AT

FROM {{source('source','listings')}}

