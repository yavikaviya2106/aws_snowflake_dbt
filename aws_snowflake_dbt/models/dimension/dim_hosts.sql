WITH source AS (
    SELECT * FROM {{ref('stg_hosts')}}
),

final AS(

SELECT
HOST_ID,
HOST_NAME,
HOST_SINCE,
IS_SUPERHOST,
RESPONSE_RATE,

DATEDIFF('YEAR',HOST_SINCE,CURRENT_DATE) AS HOST_TENURE_YEARS,
CASE
    WHEN DATEDIFF('YEAR',HOST_SINCE,CURRENT_DATE) < 1 THEN 'New-Host'
    WHEN DATEDIFF('YEAR',HOST_SINCE,CURRENT_DATE) < 3 THEN 'Established-host'
    ELSE 'Veteran-Host'
    END AS HOST_TENURE_TIER,

CASE  
    WHEN RESPONSE_RATE >= 95 THEN 'High'
    WHEN RESPONSE_RATE BETWEEN 80 AND 94 THEN 'Medium'
    WHEN RESPONSE_RATE BETWEEN 79 AND 60 THEN 'Low'
    ELSE 'Poor'
    END AS RESPONSE_TIER,

CREATED_AT

FROM source
ORDER BY HOST_SINCE
)

SELECT * FROM final